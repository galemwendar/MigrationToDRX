SELECT
    c.Name AS [Страна],
    COUNT(d.Id) AS [Количество документов]
FROM dbo.Document d
LEFT JOIN dbo.Country c ON d.CountryId = c.Id
GROUP BY c.Name
ORDER BY [Количество документов] DESC;

PRINT N'';
PRINT N'Разбивка по авторам:';

SELECT TOP 10
    r.[Type] AS [Тип],
    COUNT(d.Id) AS [Количество документов]
FROM dbo.Document d
LEFT JOIN dbo.Recipient r ON d.AuthorId = r.Id
GROUP BY r.[Type]
ORDER BY [Количество документов] DESC;

